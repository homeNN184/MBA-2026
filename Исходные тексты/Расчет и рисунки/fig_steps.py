W_IN, H_IN = 9.3, 4.0
for num, key, col, tab, what, res, verdict in STEPS:
    fig, ax = plt.subplots(figsize=(W_IN, H_IN), dpi=660)
    YM = 100 * H_IN / W_IN
    ax.set_xlim(0, 100); ax.set_ylim(0, YM); ax.axis("off")
    ax.set_aspect("equal")
    TOP, BOT, LM = YM - 0.9, 1.0, 2.0

    img = mpimg.imread(SH + "p" + key + ".png")
    ih, iw = img.shape[0], img.shape[1]
    H = TOP - BOT
    Wk = H * iw / float(ih)
    ax.add_patch(FancyBboxPatch((LM, BOT), Wk + 0.6, H,
                                boxstyle="round,pad=0,rounding_size=0.6",
                                fc="#FFFFFF", ec="#D6E3F0", lw=1.0, zorder=2))
    ax.imshow(img, extent=(LM + 0.3, LM + 0.3 + Wk, BOT + 0.3, BOT + H - 0.3),
              aspect="auto", zorder=3)

    x0 = LM + Wk + 3.0
    CW = 100 - LM - x0
    ax.add_patch(FancyBboxPatch((x0, BOT), CW, H,
                                boxstyle="round,pad=0,rounding_size=0.9",
                                fc="#FFFFFF", ec="#D6E3F0", lw=1.0, zorder=2))
    ax.add_patch(Circle((x0 + 3.4, TOP - 3.4), 2.0, fc=col, ec="none", zorder=4))
    ax.text(x0 + 3.4, TOP - 3.4, str(num), ha="center", va="center",
            fontsize=8.6, color="white", fontweight="bold", zorder=5)
    ax.text(x0 + 6.8, TOP - 3.4, "Вкладка «%s»" % tab, ha="left", va="center",
            fontsize=8.6, color=NAVY, fontweight="bold")

    y = TOP - 7.4
    ax.text(x0 + 2.6, y, "Что определяется на шаге", ha="left", va="center",
            fontsize=6.6, color=col, fontweight="bold")
    y -= 2.4
    for t in what:
        n = t.count("\n") + 1
        ax.add_patch(Circle((x0 + 3.2, y - 0.6), 0.36, fc=col, ec="none", zorder=5))
        ax.text(x0 + 4.8, y, t, ha="left", va="top", fontsize=6.0,
                color=SUB, linespacing=1.4)
        y -= n * 1.95 + 1.1

    nb = len(res)
    bh, bg = 4.2, 0.5
    y_bot_block = BOT + 8.4
    y_top_block = y_bot_block + nb * (bh + bg) - bg
    ax.text(x0 + 2.6, min(y - 0.4, y_top_block + 2.0), "Результат шага", ha="left",
            va="center", fontsize=6.6, color=col, fontweight="bold")
    yy = y_top_block
    for cap, val in res:
        ax.add_patch(FancyBboxPatch((x0 + 2.6, yy - bh), CW - 5.2, bh,
                                    boxstyle="round,pad=0,rounding_size=0.5",
                                    fc=FILL, ec="none", zorder=3))
        ax.text(x0 + 4.0, yy - 1.4, cap, ha="left", va="center",
                fontsize=5.8, color=SUB, zorder=4)
        ax.text(x0 + 4.0, yy - 3.1, val, ha="left", va="center",
                fontsize=6.6, color=NAVY, fontweight="bold", zorder=4)
        yy -= bh + bg

    ax.add_patch(FancyBboxPatch((x0 + 2.6, BOT + 1.4), CW - 5.2, 5.6,
                                boxstyle="round,pad=0,rounding_size=0.6",
                                fc="#FFFFFF", ec=col, lw=1.0, zorder=3))
    ax.text(x0 + 4.0, BOT + 5.0, "Переход к следующему шагу", ha="left",
            va="center", fontsize=5.8, color=col, fontweight="bold", zorder=4)
    ax.text(x0 + 4.0, BOT + 2.7, verdict, ha="left", va="center",
            fontsize=5.9, color=SUB, zorder=4, linespacing=1.35)

    fig.subplots_adjust(0, 0, 1, 1)
    fig.savefig("/home/claude/work/fig/step%d.png" % num, dpi=660, facecolor="white")
    plt.close(fig)
    print("step%d.png" % num)
