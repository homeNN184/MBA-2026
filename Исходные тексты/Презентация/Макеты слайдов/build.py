    for r in p0.runs[1:]:
        r._r.getparent().remove(r._r)
    r0.text=lines[0]
    for l in lines[1:]:
        np_=copy.deepcopy(p0._p); tf._txBody.append(np_)
        from pptx.text.text import _Paragraph
        pp=_Paragraph(np_,tf)
        for r in pp.runs[1:]: r._r.getparent().remove(r._r)
        pp.runs[0].text=l
