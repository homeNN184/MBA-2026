def pic(s,name,x,y,maxw,maxh):
    from PIL import Image
    w,h=Image.open(FIG+name).size; sc=min(maxw/w,maxh/h)
    pw,ph=w*sc,h*sc
    s.shapes.add_picture(FIG+name,Inches(x+(maxw-pw)/2),Inches(y+(maxh-ph)/2),Inches(pw),Inches(ph))
def style_chart(ch,legend=False):
    ch.font.size=Pt(11); ch.font.name="Arial"
    ch.has_legend=legend
    if legend:
        ch.legend.position=XL_LEGEND_POSITION.BOTTOM; ch.legend.include_in_layout=False; ch.legend.font.size=Pt(11)
    va=ch.value_axis; va.has_major_gridlines=True
    va.major_gridlines.format.line.color.rgb=RGBColor(0xD9,0xD9,0xD9); va.format.line.fill.background()
    va.tick_labels.font.size=Pt(10); ch.category_axis.tick_labels.font.size=Pt(11)

