def new_slide(title, notes):
    s=prs.slides.add_slide(LAY)
    for ph in list(s.placeholders):
        if ph.placeholder_format.idx==0: ph.text_frame.text=title
        else: ph._element.getparent().remove(ph._element)
    s.notes_slide.notes_text_frame.text=notes
    return s
def tb(s,x,y,w,h,text,size=14,bold=False,color=DARK,align=PP_ALIGN.LEFT,anchor=MSO_ANCHOR.TOP):
    t=s.shapes.add_textbox(Inches(x),Inches(y),Inches(w),Inches(h)); tf=t.text_frame; tf.word_wrap=True
    tf.margin_left=tf.margin_right=Inches(0.05); tf.margin_top=tf.margin_bottom=Inches(0.03)
    tf.vertical_anchor=anchor
    lines=text if isinstance(text,list) else [text]
    for i,l in enumerate(lines):
        p=tf.paragraphs[0] if i==0 else tf.add_paragraph()
        p.alignment=align; r=p.add_run(); r.text=l; r.font.size=Pt(size); r.font.bold=bold; r.font.color.rgb=color; r.font.name="Arial"
    return t
def card(s,x,y,w,h,head,body,hsize=13,bsize=12,fill=LIGHT,headcolor=NAVY):
    r=s.shapes.add_shape(MSO_SHAPE.RECTANGLE,Inches(x),Inches(y),Inches(w),Inches(h))
    r.fill.solid(); r.fill.fore_color.rgb=fill; r.line.fill.background(); r.shadow.inherit=False
    a=s.shapes.add_shape(MSO_SHAPE.RECTANGLE,Inches(x),Inches(y),Inches(0.07),Inches(h))
    a.fill.solid(); a.fill.fore_color.rgb=BLUE; a.line.fill.background(); a.shadow.inherit=False
    if not head: bsize=hsize
    if head: tb(s,x+0.15,y+0.08,w-0.25,0.4,head,hsize,True,headcolor)
    if body: tb(s,x+0.15,y+(0.5 if head else 0.1),w-0.25,h-(0.55 if head else 0.15),body,bsize,False,DARK,anchor=MSO_ANCHOR.TOP if head else MSO_ANCHOR.MIDDLE)
