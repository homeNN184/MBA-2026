def par(text="", size=None, bold=False, align=None, before=0, after=0, indent=1.25):
    p = d.add_paragraph()
    if text:
        r = p.add_run(text)
        r.font.name = "Times New Roman"
        if size:
            r.font.size = Pt(size)
        r.bold = bold
    pf = p.paragraph_format
    pf.space_before = Pt(before)
    pf.space_after = Pt(after)
    pf.first_line_indent = Cm(indent)
    if align is not None:
        pf.alignment = align
    return p


def h1(text):
    par(text, 14, True, WD_ALIGN_PARAGRAPH.LEFT, 16, 8, 0).paragraph_format.keep_with_next = True


def h2(text):
    par(text, 14, True, WD_ALIGN_PARAGRAPH.LEFT, 12, 6, 0).paragraph_format.keep_with_next = True


def tab(caption, head, rows, widths=None):
    cp = par(caption, 12, False, WD_ALIGN_PARAGRAPH.LEFT, 10, 4, 0)
    cp.paragraph_format.keep_with_next = True
    t = d.add_table(rows=len(rows) + 1, cols=len(head))
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for j, x in enumerate(head):
        c = t.cell(0, j).paragraphs[0]
        c.paragraph_format.line_spacing = 1.0
        c.paragraph_format.alignment = WD_ALIGN_PARAGRAPH.CENTER
        r = c.add_run(x); r.bold = True; r.font.size = Pt(11); r.font.name = "Times New Roman"
        c.paragraph_format.keep_with_next = True
    for i, row in enumerate(rows, start=1):
        for j, x in enumerate(row):
            c = t.cell(i, j).paragraphs[0]
            c.paragraph_format.line_spacing = 1.0
            c.paragraph_format.alignment = WD_ALIGN_PARAGRAPH.LEFT if j == 0 else WD_ALIGN_PARAGRAPH.CENTER
            r = c.add_run(x); r.font.size = Pt(11); r.font.name = "Times New Roman"
    if widths:
        for col, w in zip(t.columns, widths):
            for cell in col.cells:
                cell.width = Cm(w)
    par("", after=6)


