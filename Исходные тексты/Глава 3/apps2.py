def sheet_tables(doc, ws, r1, r2, c2, appn, start=1, size=8, decimals=None, expl_on=True, titles=None, wide=False):
    k = start
    for tab in generic(ws, r1, r2, c2):
        if "note" in tab: note(doc, tab["note"]); continue
        head, rows = trim(tab)
        num = f"П{appn}.{k}"; k += 1
        tab_cap(doc, num, (tab["title"] or (titles or {}).get(k - 1, "Данные листа рабочей книги")))
        rr = [[fmt(v, (decimals or {}).get(j, 3 if isinstance(v, float) and abs(v) < 10 else 2)) for j, v in enumerate(r)] for r in rows]
        grid(doc, head, rr, wid(head, rows, k=0.19), size=size, aligns=["l"] + ["r"] * (len(head) - 1) if len(head) > 2 else None, bold_last=False)
        if expl_on:
            e = explain_from(head)
            if e: expl(doc, num, e, 9)
    return k
