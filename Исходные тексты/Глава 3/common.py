def table(head, rows, aligns=None, w=None):
    """pandoc pipe table"""
    k = len(head)
    aligns = aligns or ["l"] * k
    ws = []
    for j in range(k):
        L = [len(str(r[j])) for r in rows] + [len(str(head[j])) * 0.8]
        ws.append(max(6, min(46, int(sum(L) / len(L) * 0.9 + 5))))
    if w: ws = list(w)
    sep = [(":" + "-" * w) if a == "l" else (("-" * w + ":") if a == "r" else (":" + "-" * w + ":")) for a, w in zip(aligns, ws)]
    out = ["| " + " | ".join(head) + " |", "|" + "|".join(sep) + "|"]
    for r in rows:
        out.append("| " + " | ".join(str(c).replace("|", "/") for c in r) + " |")
    return "\n".join(out)
