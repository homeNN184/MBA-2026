def pic(doc, path, cap, width=15.0, newpage=False):
    p = doc.add_paragraph(); p.alignment = AL.CENTER
    if newpage:
        p.paragraph_format.page_break_before = True
    p.paragraph_format.keep_with_next = True
    p.paragraph_format.space_after = 0
    p.add_run().add_picture(path, width=_Cm(min(width, W_AVAIL[0])))
    para(doc, cap, 12, AL.CENTER, 0, line=1.0, before=4, after=8)


