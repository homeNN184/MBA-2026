def para(txt, size=14, align=WD_ALIGN_PARAGRAPH.JUSTIFY, ind=1.25, bold=False,
         before=0, after=0, italic=False, color=None):
    p = d.add_paragraph()
    p.paragraph_format.alignment = align
    p.paragraph_format.first_line_indent = Cm(ind)
    p.paragraph_format.space_before = Pt(before)
    p.paragraph_format.space_after = Pt(after)
    r = p.add_run(txt)
    r.font.size = Pt(size); r.bold = bold; r.italic = italic
    if color is not None:
        r.font.color.rgb = color
    return p


def head(txt, size=14, before=14, after=8):
    para(txt, size, WD_ALIGN_PARAGRAPH.LEFT, 0, True, before, after, color=NAVY)


