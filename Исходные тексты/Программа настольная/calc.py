def defaults():
    d = M.P()
    out = {}
    for k in KEYS:
        v = getattr(d, k)
        out[k] = list(v) if isinstance(v, tuple) else v
    return out


def make_p(state):
    kw = {}
    for k, v in state.items():
        if k not in KEYS:
            continue
        kw[k] = tuple(v) if isinstance(v, list) else v
    return M.P(**kw)


def compute(state):
    p = make_p(state)
    R = {"p": p, "scn": {}}
    for s in SC:
        sch = M.schedule(s, p)
        rows = M.flows(s, p)
        R["scn"][s] = dict(sch=sch, rows=rows, ind=M.indicators(rows, p.rate))
    R["base"] = R["scn"]["BASE"]["ind"]["npv"]
    for s in M.INTEG:
        R["scn"][s]["adv"] = R["scn"][s]["ind"]["npv"] - R["base"]
        R["scn"][s]["out"] = M.outcomes(s, p)
    R["rates"] = []
    for i in range(10, 17):
        q = make_p(dict(state, rate=i / 100.0))
        R["rates"].append(dict(rate=i / 100.0, **{s: M.npv(M.flows(s, q)) for s in SC}))
    R["pilot"] = []
    for c in (0, 35, 70, 105, 140):
        q = make_p(dict(state, pilot_share=c / p.b_inn))
        R["pilot"].append(dict(cost=c, **{s: M.npv(M.flows(s, q)) for s in SC}))
    R["shares"] = []
    for sh in (0.10, 0.15, 0.20, 0.25, 0.30, 0.35, 0.40, 0.45, 0.50):
        q = make_p(dict(state, share_inn=sh))
        R["shares"].append(dict(share=sh, **{s: M.npv(M.flows(s, q)) for s in SC}))
    return R


def f(v, d=2):
    if v is None:
        return "—"
    try:
        if v != v or v in (float("inf"), float("-inf")):
            return "—"
    except Exception:
        return str(v)
    return ("{:,." + str(d) + "f}").format(v).replace(",", " ").replace(".", ",")


